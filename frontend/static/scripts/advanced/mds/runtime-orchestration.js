import { FILTER_CONFIG, FILTER_LOOKUP } from '../mds-constants.js';
import { createFilterDropdown } from '../mds-dropdown.js';
import { formatEnum } from '../mds-utils.js';
import {
    formatSnapshotTimestamp as formatSnapshotTimestampValue,
    normaliseSnapshotInfo as normaliseSnapshotInfoValue,
} from './metadata-helpers.js';
import {
    DEFAULT_SORT_DIRECTION,
    DEFAULT_SORT_KEY,
    SORT_NONE,
} from './sort-filter-controller.js';
import { initializeMdsState } from './state-initializer.js';
import { createStateInitializerDeps } from './state-init-deps.js';
import { createDataRuntime } from './runtime-data-runtime.js';
import { createUiRuntimeBindings } from './runtime-ui-bindings.js';
import { createBootstrapRuntimeConfig } from './runtime-bootstrap-config.js';
import { bootstrapMds } from './bootstrap.js';

export function setupMdsRuntimeOrchestration({
    getState,
    setState,
    getMdsData,
    setMdsData,
    setFilteredData,
    getHasLoaded,
    setHasLoaded,
    getIsLoading,
    setIsLoading,
    getLoadPromise,
    setLoadPromise,
    setExplorerPreloadPromise,
    clearResolvedEntryCache,
    getResolvedEntryCache,
    getLazyLoader,
    setLazyLoader,
    getBackgroundLoadingInProgress,
    setBackgroundLoadingInProgress,
    initialMdsInfo,
    customMetadataItems,
    applyFilters,
    handleCustomPanelKeydown,
    closeCustomMetadataPanel,
    openCustomMetadataPanel,
    handleCustomDropzoneDragEnter,
    handleCustomDropzoneDragLeave,
    handleCustomDrop,
    handleCustomFileInputChange,
    scheduleScrollTopButtonUpdate,
    syncHorizontalScrollPositions,
    handleSortButtonClick,
    scrollMdsSectionToTop,
    refreshMetadata,
    hideHorizontalScroll,
    handleWindowScroll,
    createDetailStickyHeader,
    updateCustomMetadataList,
    setCustomMetadataMessage,
    setupColumnResizers,
    setColumnResizersEnabled,
    deleteCustomMetadata,
    setUpdateButtonMode,
    resetSortState,
    updateOptionLists,
    scheduleHorizontalScrollMetricsUpdate,
    setStatus,
    setRetryButtonVisible,
    updateCount,
    waitForStateReady,
    normaliseCertificateBase64,
    decodeCertificate,
    hideScrollTopButton,
    scrollRowIntoView,
    setHighlightedRow,
    stabiliseColumnWidths,
    scheduleColumnResizerMetricsUpdate,
    scheduleRowHeightLock,
    isLoading,
    loadPromise,
    resetFilters,
    waitForLayoutSettled,
    waitForRowByKey,
    updateSortButtonState,
    formatInitialExplorerStatus,
    getInitialSnapshotPayload,
}) {
    let uiBindings = null;

    const initializeState = root =>
        initializeMdsState(
            root,
            createStateInitializerDeps({
                FILTER_CONFIG,
                FILTER_LOOKUP,
                DEFAULT_SORT_KEY,
                DEFAULT_SORT_DIRECTION,
                SORT_NONE,
                createFilterDropdown,
                formatEnum,
                normaliseSnapshotInfo: normaliseSnapshotInfoValue,
                initialMdsInfo,
                customMetadataItems,
                getState,
                applyFilters,
                handleCustomPanelKeydown,
                closeCustomMetadataPanel,
                openCustomMetadataPanel,
                handleCustomDropzoneDragEnter,
                handleCustomDropzoneDragLeave,
                handleCustomDrop,
                handleCustomFileInputChange,
                scheduleScrollTopButtonUpdate,
                syncHorizontalScrollPositions,
                handleSortButtonClick,
                scrollMdsSectionToTop,
                refreshMetadata,
                closeCertificatePage: () => uiBindings?.closeCertificatePage?.(),
                closeAuthenticatorModal: () => uiBindings?.closeAuthenticatorModal?.(),
                openAuthenticatorRawWindow: () => uiBindings?.openAuthenticatorRawWindow?.(),
                clearRowHighlight: () => uiBindings?.clearRowHighlight?.(),
                hideScrollTopButton,
                hideHorizontalScroll,
                scheduleHorizontalScrollMetricsUpdate,
                createDetailStickyHeader,
                updateCustomMetadataList,
                setCustomMetadataMessage,
                setupColumnResizers,
                setColumnResizersEnabled,
                deleteCustomMetadata,
            }),
        );

    const dataBindings = createDataRuntime({
        getState,
        getMdsData,
        setMdsData,
        setFilteredData,
        getHasLoaded,
        setHasLoaded,
        getIsLoading,
        setIsLoading,
        getLoadPromise,
        setLoadPromise,
        setExplorerPreloadPromise,
        clearResolvedEntryCache,
        getResolvedEntryCache,
        getLazyLoader,
        setLazyLoader,
        getBackgroundLoadingInProgress,
        setBackgroundLoadingInProgress,
        setUpdateButtonMode,
        resetSortState,
        formatSnapshotTimestamp: formatSnapshotTimestampValue,
        initialMdsInfo,
        updateOptionLists,
        applyFilters,
        scheduleHorizontalScrollMetricsUpdate,
        setStatus,
        setRetryButtonVisible,
        setColumnResizersEnabled,
        updateCount,
        waitForStateReady,
        normaliseCertificateBase64,
        decodeCertificate,
    });

    uiBindings = createUiRuntimeBindings({
        getState,
        getMdsData,
        resolveMetadataEntry: dataBindings.resolveMetadataEntry,
        normaliseCertificateBase64,
        decodeCertificate,
        hideScrollTopButton,
        scheduleScrollTopButtonUpdate,
        scrollRowIntoView,
        setHighlightedRow,
        stabiliseColumnWidths,
        scheduleColumnResizerMetricsUpdate,
        scheduleHorizontalScrollMetricsUpdate,
        scheduleRowHeightLock,
        waitForStateReady,
        isLoading,
        loadPromise,
        resetFilters,
        applyFilters,
        waitForLayoutSettled,
        waitForRowByKey,
    });

    bootstrapMds(
        createBootstrapRuntimeConfig({
            handleWindowScroll,
            initializeState: root => {
                const state = initializeState(root);
                setState(state);
                return state;
            },
            updateSortButtonState,
            setUpdateButtonMode,
            formatInitialExplorerStatus,
            setStatus,
            getState,
            getInitialSnapshotPayload,
            applyExplorerSnapshot: dataBindings.applyExplorerSnapshot,
            loadMdsData: dataBindings.loadMdsData,
            openAuthenticatorModalByAaguid: uiBindings.openAuthenticatorModalByAaguid,
            focusAuthenticatorByAaguid: uiBindings.focusAuthenticatorByAaguid,
            highlightAuthenticatorRowByAaguid: uiBindings.highlightAuthenticatorRowByAaguid,
            finaliseHighlightedAuthenticatorRow: uiBindings.finaliseHighlightedAuthenticatorRow,
            waitForMetadataLoad: dataBindings.waitForMetadataLoad,
            getMdsLoadStateSnapshot: dataBindings.getMdsLoadStateSnapshot,
            resolveEntryByAaguid: uiBindings.resolveEntryByAaguid,
        }),
    );

    return {
        ...dataBindings,
        ...uiBindings,
    };
}
